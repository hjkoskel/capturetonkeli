#!/usr/bin/env python3
"""Generate smoke_symbols.c from firmware/idf-api.txt (docs/10 §5), or check
that every `kconfig` entry exists in a build's sdkconfig.json.

  gen_smoke.py gen  IDF_API_TXT OUT_C
  gen_smoke.py kconfig IDF_API_TXT SDKCONFIG_JSON
"""
import json
import sys

# macros that are not plain values
SPECIAL = {
    "WIFI_INIT_CONFIG_DEFAULT": "{ wifi_init_config_t c = WIFI_INIT_CONFIG_DEFAULT(); (void)c; }",
    "__NOINIT_ATTR": None,  # attribute: emitted at file scope
    "IRAM_ATTR": None,
    "REG_SET_FIELD": None,  # function-like; exercised by sys_esp.c
    "xTaskNotifyGive": "(void)xTaskNotifyGive((TaskHandle_t)0);",
    "ulTaskNotifyTake": "(void)ulTaskNotifyTake(pdTRUE, 0);",
}


def parse(path):
    items = []
    with open(path) as f:
        for n, line in enumerate(f, 1):
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) != 2:
                sys.exit(f"{path}:{n}: expected '<kind> <name>'")
            items.append((parts[0], parts[1], n))
    return items


def gen(api, out):
    items = parse(api)
    headers = [n for k, n, _ in items if k == "header"]
    c = ["/* GENERATED by gen_smoke.py from idf-api.txt. DO NOT EDIT. */",
         "#include \"freertos/FreeRTOS.h\""]
    c += [f"#include \"{h}\"" for h in headers if h != "freertos/FreeRTOS.h"]
    c += ["#include \"freertos/task.h\"", "#include <stddef.h>", "",
          "void ctk_smoke_refs(int never);"]
    for k, n, _ in items:
        if k == "macro" and n == "__NOINIT_ATTR":
            c.append("static __NOINIT_ATTR int s_smoke_noinit;")
        if k == "macro" and n == "IRAM_ATTR":
            c.append("static void IRAM_ATTR smoke_iram(void) {}")
    fields = {}
    for k, n, _ in items:
        if k == "field":
            t, f = n.split(".", 1)
            fields.setdefault(t, []).append(f)
    for i, (t, fs) in enumerate(fields.items()):
        c.append(f"static void smoke_fields_{i}(const {t} *p)\n{{")
        c += [f"    (void)p->{f};" for f in fs]
        c.append("}")
    c.append("\nvolatile const void *ctk_smoke_sink;\n")
    c.append("void ctk_smoke_refs(int never)\n{\n    if (!never) {\n        return;\n    }")
    for k, n, _ in items:
        if k == "func":
            c.append(f"    ctk_smoke_sink = (const void *)&{n};")
        elif k == "type":
            c.append(f"    (void)sizeof({n});")
        elif k == "enum":
            c.append(f"    (void)({n});")
        elif k == "macro":
            if n in SPECIAL:
                if SPECIAL[n]:
                    c.append("    " + SPECIAL[n])
            else:
                c.append(f"    (void)({n});")
    for i, t in enumerate(fields):
        c.append(f"    smoke_fields_{i}(NULL);")
    if any(n == "__NOINIT_ATTR" for _, n, _ in items):
        c.append("    s_smoke_noinit++;")
    if any(n == "IRAM_ATTR" for _, n, _ in items):
        c.append("    smoke_iram();")
    c.append("}")
    with open(out, "w") as f:
        f.write("\n".join(c) + "\n")


def kconfig(api, sdkjson):
    with open(sdkjson) as f:
        cfg = json.load(f)
    missing = [n for k, n, _ in parse(api) if k == "kconfig" and n.removeprefix("CONFIG_") not in cfg]
    if missing:
        sys.exit("unknown Kconfig symbols (re-audit docs/10): " + ", ".join(missing))
    print(f"kconfig: all {sum(1 for k, *_ in parse(api) if k == 'kconfig')} symbols exist")


if __name__ == "__main__":
    if len(sys.argv) == 4 and sys.argv[1] == "gen":
        gen(sys.argv[2], sys.argv[3])
    elif len(sys.argv) == 4 and sys.argv[1] == "kconfig":
        kconfig(sys.argv[2], sys.argv[3])
    else:
        sys.exit(__doc__)
