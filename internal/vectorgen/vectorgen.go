func genCountries() {
	c := newC("tv_countries.h", "TV_COUNTRIES_H")
	codes := regdom.Codes()
	sort.Strings(codes)
	var rows []string
	type js struct {
		Code  string  `json:"code"`
		SChan uint8   `json:"schan"`
		NChan uint8   `json:"nchan"`
		G5    []uint8 `json:"ch5"`
	}
	var jl []js
	for _, cc := range codes {
		r := regdom.Countries[cc]
		g5 := make([]string, len(r.G5))
		for i, v := range r.G5 {
			g5[i] = fmt.Sprint(v)
		}
		fmt.Fprintf(&c.buf, "static const uint8_t tv_cc5_%s[] = {%s};\n", strings.ToLower(cc), strings.Join(g5, ","))
		rows = append(rows, fmt.Sprintf("    {\"%s\", %d, %d, tv_cc5_%s, %d},", cc, r.G24[0], r.G24[1], strings.ToLower(cc), len(r.G5)))
		jl = append(jl, js{cc, r.G24[0], r.G24[1], r.G5})
	}
	writeJSON("countries.json", jl)
	// web UI copy (same table; js/regdom.js is generated, never edit by hand)
	var jsb strings.Builder
	jsb.WriteString("// GENERATED by internal/vectorgen (go generate ./...) from ctp/regdom. DO NOT EDIT.\n")
	jsb.WriteString("// Measured ESP-IDF v6.0.2 channel table (docs/measurements/channel-map-v6.0.2.json).\n")
	jsb.WriteString("export const COUNTRIES = {\n")
	for _, c := range jl {
		g5 := make([]string, len(c.G5))
		for i, v := range c.G5 {
			g5[i] = fmt.Sprint(v)
		}
		fmt.Fprintf(&jsb, "  %q: { schan: %d, nchan: %d, ch5: [%s] },\n", c.Code, c.SChan, c.NChan, strings.Join(g5, ", "))
	}
	jsb.WriteString("};\n")
	must(os.WriteFile(filepath.Join(*out, "..", "js", "regdom.js"), []byte(jsb.String()), 0o644))
	fmt.Fprintf(&c.buf, "\n/* MODEL of the ESP-IDF country table (ctp/regdom); corrected after the M4 channel-map measurement. */\ntypedef struct { const char *cc; uint8_t schan, nchan; const uint8_t *ch5; size_t n5; } tv_country_t;\nstatic const tv_country_t tv_countries[] = {\n%s\n};\n#define TV_COUNTRIES_N (sizeof tv_countries / sizeof tv_countries[0])\n", strings.Join(rows, "\n"))
	c.close()
}

