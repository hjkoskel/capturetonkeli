// Message vectors carry the field values flattened in declaration order
// ("fields"), so C tests can check decode/encode without a JSON parser.
// Field order per message is the doc 03 §6.1 byte order; byte arrays are
// expanded one element per field.
func genMessages() {
	type tc struct {
		Name   string  `json:"name"`
		Type   uint8   `json:"type"`
		Dir    string  `json:"dir"` // "req" (host→device) or "rsp" (device→host)
		Fields []int64 `json:"fields"`
		Body   string  `json:"body_hex"`
		Extra  bool    `json:"longer_body,omitempty"`
		Note   string  `json:"note,omitempty"`
	}
	var cases []tc
	add := func(name string, typ uint8, dir string, fields []int64, body []byte) {
		cases = append(cases, tc{Name: name, Type: typ, Dir: dir, Fields: fields, Body: hx(body)})
		if dir == "req" {
			cases = append(cases, tc{Name: name + " (+trailing)", Type: typ, Dir: dir, Fields: fields, Body: hx(append(append([]byte(nil), body...), 0xAA, 0x55)), Extra: true})
		}
	}
	bs := func(b []byte) []int64 {
		out := make([]int64, len(b))
		for i, x := range b {
			out[i] = int64(x)
		}
		return out
	}
	cat := func(p ...[]int64) []int64 {
		var o []int64
		for _, x := range p {
			o = append(o, x...)
		}
		return o
	}
	add("HELLO", wire.TypeHello, "req", []int64{0xDEADBEEF, 1}, wire.Hello{HostNonce: 0xDEADBEEF, HostProtoVer: 1}.AppendBinary(nil))
	add("PING", wire.TypePing, "req", []int64{123456}, wire.Ping{HostTimeMS: 123456}.AppendBinary(nil))
	add("SET_CHANNEL", wire.TypeSetChannel, "req", []int64{149, 2}, wire.SetChannel{Channel: 149, BW: wire.BW40Minus}.AppendBinary(nil))
	cc := wire.MakeCountry("FI", 1, 1, 13)
	add("SET_COUNTRY", wire.TypeSetCountry, "req", []int64{'F', 'I', 0, 1, 1, 13}, cc.AppendBinary(nil))
	add("SET_SNAPLEN", wire.TypeSetSnaplen, "req", []int64{1500}, wire.SetSnaplen{Snaplen: 1500}.AppendBinary(nil))
	add("SET_DRIVER_MASK", wire.TypeSetDriverMask, "req", []int64{0x7, 0xFF800000}, wire.SetDriverMask{TypeMask: 7, CtrlMask: 0xFF800000}.AppendBinary(nil))
	add("CAPTURE", wire.TypeCapture, "req", []int64{1}, wire.Capture{On: true}.AppendBinary(nil))
	add("GET_STATS", wire.TypeGetStats, "req", []int64{1}, wire.GetStats{ResetAfterRead: true}.AppendBinary(nil))
	add("REBOOT", wire.TypeReboot, "req", []int64{1}, wire.Reboot{Mode: wire.RebootDownload}.AppendBinary(nil))

	bid := [8]byte{0x77, 0xb0, 0xe4, 0x12, 0xa8, 0xc3, 0xd9, 0x01}
	mac := [6]byte{0x02, 0xc5, 0x11, 0x22, 0x33, 0x44}
	di := wire.DeviceInfo{ProtoVer: 1, FwVersion: 0x01030002, FwFlags: 5, FwBuildID: bid, MAC: mac, Caps: 7, MaxFrame: 4128, MaxRules: 16,
		DeviceTimeUS: 0x0102030405060708, HostNonce: 0xCAFEBABE, ResetReason: wire.ResetAssert, StateFlags: 1}
	add("RSP_OK DeviceInfo", wire.TypeRspOK, "rsp", cat([]int64{1, 0x01030002, 5}, bs(bid[:]), bs(mac[:]), []int64{7, 4128, 16, 0x0102030405060708, 0xCAFEBABE, 6, 1}), di.AppendBinary(nil))
	add("RSP_OK Pong", wire.TypeRspOK, "rsp", []int64{99, 1234567}, wire.Pong{HostTimeMS: 99, DeviceTimeUS: 1234567}.AppendBinary(nil))
	cfg := wire.Config{CfgGen: 9, Channel: 44, BW: wire.BW40Plus, Band: wire.Band5G, Country: wire.MakeCountry("FI", 0, 1, 13), Snaplen: 256,
		TypeMask: 0xFFFFFFFF, CtrlMask: 0xFF800000, CaptureOn: true, NRules: 3, RulesCRC32: 0x1A2B3C4D}
	add("RSP_OK Config", wire.TypeRspOK, "rsp", []int64{9, 44, 1, 1, 'F', 'I', 0, 0, 1, 13, 256, 0xFFFFFFFF, 0xFF800000, 1, 3, 0x1A2B3C4D}, cfg.AppendBinary(nil))
	boot := wire.BootConfig()
	add("RSP_OK boot Config", wire.TypeRspOK, "rsp", []int64{0, 1, 0, 0, '0', '1', 0, 0, 1, 11, 0, 0xFFFFFFFF, 0xFF800000, 0, 0, int64(wire.EmptyFilterCRC)}, boot.AppendBinary(nil))
	st := wire.Stats{DeviceTimeUS: 5_000_000, RxTotal: 1, RxPassed: 2, DropRing: 3, DropFCS: 4, TxFrames: 5, TxBytes: 6, HostRxCRCErr: 7, HostRxOversize: 8, RingHighWater: 42, Channel: 6, NoiseFloor: -95, FlashWrites: 0}
	add("EVT_STATS", wire.TypeEvtStats, "rsp", []int64{5_000_000, 1, 2, 3, 4, 5, 6, 7, 8, 42, 6, -95, 0}, st.AppendBinary(nil))
	add("RSP_ERR", wire.TypeRspErr, "rsp", []int64{4, 0x3002}, wire.RspErr{Code: wire.ErrChannelNotAllowed, EspErr: 0x3002, Detail: "not in country table"}.AppendBinary(nil))
	cases[len(cases)-1].Note = "detail \"not in country table\""
	add("EVT_RESET", wire.TypeEvtReset, "rsp", []int64{6, 0x01030002, 1}, wire.Reset{Reason: wire.ResetAssert, FwVersion: 0x01030002, StateFlags: 1, Detail: "proto.c:123"}.AppendBinary(nil))
	cases[len(cases)-1].Note = "detail \"proto.c:123\""
	pm := wire.PktMeta{TsUS: 0x0000_0001_0203_0405, Channel: 36, Flags: wire.PktTruncated | wire.Pkt5GHz, RSSI: -61, Noise: -96, Rate: 7, BBFormat: wire.BBHT, OrigLen: 1500, CapLen: 4, RxSeq: 65535}
	add("PKT", wire.TypePkt, "rsp", []int64{0x0000_0001_0203_0405, 36, 6, -61, -96, 7, 2, 1500, 4, 65535}, append(pm.AppendBinary(nil), 0x88, 0x02, 0x2c, 0x00))
	cases[len(cases)-1].Note = "data 88 02 2c 00"

	// self-check: every vector decodes with the reference structs
	writeJSON("messages.json", cases)
	c := newC("tv_messages.h", "TV_MESSAGES_H")
	var rows []string
	for _, m := range cases {
		b, _ := hex.DecodeString(m.Body)
		f := make([]string, len(m.Fields))
		for i, v := range m.Fields {
			if v < 0 {
				f[i] = fmt.Sprintf("%d", v)
			} else {
				f[i] = fmt.Sprintf("%dull", v)
			}
		}
		fname := c.bytesVar("tv_msg_body", b)
		fmt.Fprintf(&c.buf, "static const int64_t tv_msg_fields_%d[] = {%s};\n", c.n, strings.Join(f, ", "))
		rows = append(rows, fmt.Sprintf("    {%q, 0x%02x, %v, %v, tv_msg_fields_%d, %d, %s, %d},", m.Name, m.Type, m.Dir == "req", m.Extra, c.n, len(m.Fields), fname, len(b)))
	}
	fmt.Fprintf(&c.buf, "\ntypedef struct { const char *name; uint8_t type; bool is_req; bool longer; const int64_t *fields; size_t n_fields; const uint8_t *body; size_t len; } tv_msg_t;\nstatic const tv_msg_t tv_msgs[] = {\n%s\n};\n#define TV_MSGS_N (sizeof tv_msgs / sizeof tv_msgs[0])\n", strings.Join(rows, "\n"))
	c.close()
}

