func genFilters() {
	type enc struct {
		Name   string          `json:"name"`
		Filter json.RawMessage `json:"filter"`
		Body   string          `json:"body_hex"`
		CRC    uint32          `json:"crc"`
	}
	type match struct {
		Filter  int    `json:"filter"` // index into filter_encode.json
		Frame   int    `json:"frame"`  // index into frames_hex
		Flags   uint8  `json:"flags"`
		RSSI    int8   `json:"rssi"`
		OrigLen uint16 `json:"orig_len"`
		Expect  bool   `json:"expect"`
	}
	type invalid struct {
		Name string `json:"name"`
		Body string `json:"body_hex"`
	}
	i8 := func(v int8) *int8 { return &v }
	u16 := func(v uint16) *uint16 { return &v }
	mac := []byte{0x02, 0x11, 0x22, 0x33, 0x44, 0x05}
	named := []struct {
		name string
		s    filter.Set
	}{
		{"empty", filter.Set{}},
		{"beacons", filter.Set{Rules: []filter.Rule{filter.Beacons()}}},
		{"drop beacons", filter.Set{Rules: []filter.Rule{filter.DropBeacons()}}},
		{"mgmt or ctrl", filter.Set{Rules: []filter.Rule{filter.Mgmt(), filter.Ctrl()}}},
		{"data from mac", filter.Set{Rules: []filter.Rule{{Enabled: true, Terms: []filter.Term{filter.Data().Terms[0], filter.FromMAC(mac).Terms[0]}}}}},
		{"eapol", filter.Set{Rules: filter.EAPOL()}},
		{"deauth/disassoc", filter.Set{Rules: filter.DeauthDisassoc()}},
		{"globals", filter.Set{Global: filter.Global{DropFCSErr: true, RSSIMin: i8(-70), LenMin: u16(20), LenMax: u16(400)}}},
		{"beacons + globals", filter.Set{Rules: []filter.Rule{filter.Beacons()}, Global: filter.Global{DropFCSErr: true, RSSIMin: i8(-60)}}},
		{"nibble wildcard", filter.Set{Rules: []filter.Rule{{Enabled: true, Terms: []filter.Term{mustT(4, "ff ff ?? ff")}}}}},
		{"negated far offset", filter.Set{Rules: []filter.Rule{{Enabled: true, Terms: []filter.Term{func() filter.Term { t := mustT(3000, "aa"); t.Negate = true; return t }()}}}}},
		{"16-byte term at 4080", filter.Set{Rules: []filter.Rule{{Enabled: true, Terms: []filter.Term{mustT(4080, "00 ?? 00 00 00 00 00 00 00 00 00 00 00 00 00 ?0")}}}}},
		{"disabled rule ignored", filter.Set{Rules: []filter.Rule{func() filter.Rule { r := filter.Beacons(); r.Enabled = false; return r }(), filter.ProbeReq()}}},
		{"max rules", maxSet()},
	}
	var encs []enc
	c := newC("tv_filter.h", "TV_FILTER_H")
	var encRows []string
	bodies := make([][]byte, len(named))
	for i, n := range named {
		b, err := n.s.Encode()
		must(err)
		bodies[i] = b
		js, _ := json.Marshal(n.s)
		encs = append(encs, enc{n.name, js, hx(b), codec.CRC32(b)})
		encRows = append(encRows, fmt.Sprintf("    {%q, %s, %d, 0x%08xu},", n.name, c.bytesVar("tv_flt_body", b), len(b), codec.CRC32(b)))
	}
	writeJSON("filter_encode.json", encs)
	if len(bodies[len(bodies)-1]) != 2328 {
		must(fmt.Errorf("max filter body %d != 2328", len(bodies[len(bodies)-1])))
	}

	// frames for matching
	rng := rand.New(rand.NewSource(11))
	frames := sampleFrames(rng, mac)
	var ms []match
	for fi, n := range named {
		for fri, fr := range frames {
			for _, meta := range []wire.PktMeta{
				{RSSI: -50, OrigLen: uint16(len(fr))},
				{RSSI: -80, OrigLen: uint16(len(fr)), Flags: wire.PktFCSErr},
			} {
				ms = append(ms, match{fi, fri, meta.Flags, meta.RSSI, meta.OrigLen, n.s.Match(fr, meta)})
			}
		}
	}
	fhex := make([]string, len(frames))
	var frows []string
	for i, fr := range frames {
		fhex[i] = hx(fr)
		frows = append(frows, fmt.Sprintf("    {%s, %d},", c.bytesVar("tv_flt_frame", fr), len(fr)))
	}
	writeJSON("filter_match.json", map[string]any{"frames_hex": fhex, "cases": ms})
	var mrows []string
	for _, m := range ms {
		mrows = append(mrows, fmt.Sprintf("    {%d, %d, 0x%02x, %d, %d, %v},", m.Filter, m.Frame, m.Flags, m.RSSI, m.OrigLen, m.Expect))
	}

	bad := []invalid{
		{"short header", "00000000"},
		{"zero terms", "010000000000000000"},
		{"unknown gflags", "0010000000000000"},
		{"reserved nonzero", "0000000100000000"},
		{"trailing byte", "0000000000000000ee"},
		{"term len 0", "0100000000000000010000" + "0000"},
		{"term len 17", "01000000000000000100001100"},
		{"unknown tflags", "010000000000000001000001028000ff"},
		{"value/mask truncated", "0100000000000000010000010080"},
		{"17 rules", "1100000000000000"},
		{"5 terms", "010000000000000005"},
	}
	for _, b := range bad {
		raw, _ := hex.DecodeString(b.Body)
		if _, err := filter.Decode(raw); err == nil {
			must(fmt.Errorf("invalid vector %q accepted by reference decoder", b.Name))
		}
	}
	writeJSON("filter_invalid.json", bad)
	var irows []string
	for _, b := range bad {
		raw, _ := hex.DecodeString(b.Body)
		irows = append(irows, fmt.Sprintf("    {%q, %s, %d},", b.Name, c.bytesVar("tv_flt_bad", raw), len(raw)))
	}
	fmt.Fprintf(&c.buf, "\ntypedef struct { const char *name; const uint8_t *body; size_t len; uint32_t crc; } tv_flt_enc_t;\nstatic const tv_flt_enc_t tv_flt_enc[] = {\n%s\n};\n#define TV_FLT_ENC_N (sizeof tv_flt_enc / sizeof tv_flt_enc[0])\n", strings.Join(encRows, "\n"))
	fmt.Fprintf(&c.buf, "\ntypedef struct { const uint8_t *data; size_t len; } tv_flt_frame_t;\nstatic const tv_flt_frame_t tv_flt_frames[] = {\n%s\n};\n", strings.Join(frows, "\n"))
	fmt.Fprintf(&c.buf, "\ntypedef struct { int filter; int frame; uint8_t flags; int8_t rssi; uint16_t orig_len; bool expect; } tv_flt_match_t;\nstatic const tv_flt_match_t tv_flt_match[] = {\n%s\n};\n#define TV_FLT_MATCH_N (sizeof tv_flt_match / sizeof tv_flt_match[0])\n", strings.Join(mrows, "\n"))
	fmt.Fprintf(&c.buf, "\ntypedef struct { const char *name; const uint8_t *body; size_t len; } tv_flt_bad_t;\nstatic const tv_flt_bad_t tv_flt_bad[] = {\n%s\n};\n#define TV_FLT_BAD_N (sizeof tv_flt_bad / sizeof tv_flt_bad[0])\n", strings.Join(irows, "\n"))
	c.close()
}

func mustT(off uint16, p string) filter.Term {
	t, err := filter.ParseTerm(off, p)
	must(err)
	return t
}

func maxSet() filter.Set {
	var s filter.Set
	for r := 0; r < filter.MaxRules; r++ {
		var terms []filter.Term
		for k := 0; k < filter.MaxTerms; k++ {
			v := bytes.Repeat([]byte{byte(r*4 + k)}, 16)
			terms = append(terms, filter.Term{Offset: uint16(r*64 + k*16), Value: v, Mask: bytes.Repeat([]byte{0xff}, 16), Negate: k == 3})
		}
		s.Rules = append(s.Rules, filter.Rule{Enabled: true, Terms: terms})
	}
	return s
}

func sampleFrames(rng *rand.Rand, mac []byte) [][]byte {
	hdr := func(fc0, fc1 byte, a1, a2, a3 []byte) []byte {
		f := []byte{fc0, fc1, 0, 0}
		f = append(f, a1...)
		f = append(f, a2...)
		f = append(f, a3...)
		return append(f, 0x10, 0x00)
	}
	bc := []byte{0xff, 0xff, 0xff, 0xff, 0xff, 0xff}
	ap := []byte{0x02, 0xaa, 0xbb, 0xcc, 0xdd, 0xee}
	fcs := func(f []byte) []byte { return binary.LittleEndian.AppendUint32(f, codec.CRC32(f)) }
	llc := []byte{0xaa, 0xaa, 0x03, 0, 0, 0, 0x88, 0x8e}
	var out [][]byte
	out = append(out,
		fcs(append(hdr(0x80, 0, bc, ap, ap), make([]byte, 30)...)),                    // beacon
		fcs(hdr(0x40, 0, bc, mac, bc)),                                                // probe req
		fcs(append(hdr(0x50, 0, mac, ap, ap), make([]byte, 20)...)),                   // probe resp
		fcs(append([]byte{0xd4, 0, 0, 0}, mac...)),                                    // ACK (14 B)
		fcs(append(append([]byte{0xb4, 0, 0, 0}, ap...), mac...)),                     // RTS
		fcs(append(hdr(0x08, 0x01, ap, mac, ap), llc...)),                             // data from mac, EAPOL non-QoS
		fcs(append(append(hdr(0x88, 0x01, ap, mac, ap), 0, 0), llc...)),               // QoS EAPOL
		fcs(append(append(hdr(0x88, 0x02, mac, ap, ap), 0, 0), make([]byte, 400)...)), // QoS data to mac
		fcs(hdr(0xc0, 0, mac, ap, ap)),                                                // deauth
		fcs(hdr(0xa0, 0, mac, ap, ap)),                                                // disassoc
		[]byte{0x80},                                                                  // 1-byte runt
		nil,                                                                           // empty
	)
	big := make([]byte, 4096)
	rng.Read(big)
	big[0] = 0x08
	out = append(out, big)
	for i := 0; i < 4; i++ {
		f := make([]byte, 10+rng.Intn(120))
		rng.Read(f)
		out = append(out, f)
	}
	return out
}

