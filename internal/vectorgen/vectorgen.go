var out *string

type genErr struct{ err error }

// Generate writes all vectors into dir (and dir/c).
func Generate(dir string) (err error) {
	out = &dir
	defer func() {
		if x := recover(); x != nil {
			if g, ok := x.(genErr); ok {
				err = g.err
				return
			}
			panic(x)
		}
	}()
	must(os.MkdirAll(filepath.Join(*out, "c"), 0o755))
	genCOBS()
	genCRC()
	genFrames()
	genMessages()
	genFilters()
	genCountries()
	genPcapng()
	return nil
}

func must(err error) {
	if err != nil {
		panic(genErr{fmt.Errorf("vectorgen: %w", err)})
	}
}

func writeJSON(name string, v any) {
	b, err := json.MarshalIndent(v, "", "  ")
	must(err)
	must(os.WriteFile(filepath.Join(*out, name), append(b, '\n'), 0o644))
}

type cfile struct {
	name string
	buf  bytes.Buffer
	n    int
}

func newC(name, guard string) *cfile {
	c := &cfile{name: name}
	fmt.Fprintf(&c.buf, "/* GENERATED by internal/vectorgen (go generate ./...). DO NOT EDIT. */\n#ifndef %s\n#define %s\n#include <stddef.h>\n#include <stdint.h>\n#include <stdbool.h>\n\n", guard, guard)
	return c
}

// bytesVar emits a static array and returns its name ("NULL" for empty).
func (c *cfile) bytesVar(prefix string, b []byte) string {
	if len(b) == 0 {
		return "NULL"
	}
	c.n++
	name := fmt.Sprintf("%s_%d", prefix, c.n)
	fmt.Fprintf(&c.buf, "static const uint8_t %s[%d] = {", name, len(b))
	for i, x := range b {
		if i%16 == 0 {
			c.buf.WriteString("\n    ")
		}
		fmt.Fprintf(&c.buf, "0x%02x,", x)
	}
	c.buf.WriteString("\n};\n")
	return name
}

func (c *cfile) close() {
	c.buf.WriteString("\n#endif\n")
	must(os.WriteFile(filepath.Join(*out, "c", c.name), c.buf.Bytes(), 0o644))
}

func hx(b []byte) string { return hex.EncodeToString(b) }

// ---- cobs -------------------------------------------------------------------

func genCOBS() {
	type tc struct {
		Name string `json:"name"`
		In   string `json:"in_hex"`
		Out  string `json:"out_hex"`
	}
	nz := func(n int) []byte {
		b := make([]byte, n)
		for i := range b {
			b[i] = byte(1 + i%255)
		}
		return b
	}
	ins := []struct {
		name string
		b    []byte
	}{
		{"empty", nil}, {"zero", []byte{0}}, {"two zeros", []byte{0, 0}},
		{"mixed", []byte{0x11, 0x22, 0x00, 0x33}}, {"trailing zero", []byte{0x11, 0x00}},
		{"253 nonzero", nz(253)}, {"254 nonzero", nz(254)}, {"255 nonzero", nz(255)}, {"256 nonzero", nz(256)},
		{"all zero 10", make([]byte, 10)}, {"254 then zero", append(nz(254), 0)},
	}
	rng := rand.New(rand.NewSource(7))
	for i := 0; i < 6; i++ {
		b := make([]byte, rng.Intn(700))
		rng.Read(b)
		ins = append(ins, struct {
			name string
			b    []byte
		}{fmt.Sprintf("random %d", i), b})
	}
	var js []tc
	c := newC("tv_cobs.h", "TV_COBS_H")
	var rows []string
	for _, in := range ins {
		enc := codec.COBSEncode(nil, in.b)
		js = append(js, tc{in.name, hx(in.b), hx(enc)})
		rows = append(rows, fmt.Sprintf("    {%q, %s, %d, %s, %d},", in.name, c.bytesVar("tv_cobs_in", in.b), len(in.b), c.bytesVar("tv_cobs_out", enc), len(enc)))
	}
	writeJSON("cobs.json", js)
	fmt.Fprintf(&c.buf, "\ntypedef struct { const char *name; const uint8_t *in; size_t in_len; const uint8_t *out; size_t out_len; } tv_cobs_t;\nstatic const tv_cobs_t tv_cobs[] = {\n%s\n};\n#define TV_COBS_N (sizeof tv_cobs / sizeof tv_cobs[0])\n", strings.Join(rows, "\n"))
	c.close()
}

// ---- crc ----------------------------------------------------------------------

func genCRC() {
	type tc struct {
		In  string `json:"in_hex"`
		CRC uint32 `json:"crc"`
	}
	ins := [][]byte{nil, []byte("123456789"), make([]byte, 8), bytes.Repeat([]byte{0xff}, 64)}
	rng := rand.New(rand.NewSource(3))
	for i := 0; i < 5; i++ {
		b := make([]byte, 1+rng.Intn(3000))
		rng.Read(b)
		ins = append(ins, b)
	}
	var js []tc
	c := newC("tv_crc32.h", "TV_CRC32_H")
	var rows []string
	for _, in := range ins {
		v := codec.CRC32(in)
		js = append(js, tc{hx(in), v})
		rows = append(rows, fmt.Sprintf("    {%s, %d, 0x%08xu},", c.bytesVar("tv_crc_in", in), len(in), v))
	}
	writeJSON("crc32.json", js)
	fmt.Fprintf(&c.buf, "\ntypedef struct { const uint8_t *in; size_t len; uint32_t crc; } tv_crc32_t;\nstatic const tv_crc32_t tv_crc32[] = {\n%s\n};\n#define TV_CRC32_N (sizeof tv_crc32 / sizeof tv_crc32[0])\n", strings.Join(rows, "\n"))
	c.close()
}

// ---- frames -----------------------------------------------------------------

func genFrames() {
	type hdr struct {
		Ver, Type  uint8
		Seq, ReqID uint16
		Flags      uint8
		CfgGen     uint8
	}
	type valid struct {
		Header hdr    `json:"header"`
		Body   string `json:"body_hex"`
		Wire   string `json:"wire_hex"`
	}
	type stream struct {
		Name    string `json:"name"`
		Stream  string `json:"stream_hex"`
		Frames  int    `json:"frames"`
		CRCErr  int    `json:"crc_errors"`
		COBSErr int    `json:"cobs_errors"`
		Over    int    `json:"oversize"`
		Short   int    `json:"short"`
		ReqIDs  []int  `json:"req_ids"`
	}
	c := newC("tv_frames.h", "TV_FRAMES_H")
	var vs []valid
	var rows []string
	hs := []wire.Header{
		{Ver: 1, Type: wire.TypeHello, Seq: 0, ReqID: 1},
		{Ver: 1, Type: wire.TypeRspOK, Seq: 0x1234, ReqID: 0xBEEF, Flags: 2, CfgGen: 7},
		{Ver: 1, Type: wire.TypePkt, Seq: 0xFFFF, CfgGen: 0xFF},
	}
	bodies := [][]byte{wire.Hello{HostNonce: 0xDEADBEEF, HostProtoVer: 1}.AppendBinary(nil), wire.BootConfig().AppendBinary(nil), bytes.Repeat([]byte{0, 1}, 300)}
	for i, h := range hs {
		w := codec.EncodeFrame(nil, h, bodies[i])
		vs = append(vs, valid{hdr(h), hx(bodies[i]), hx(w)})
		rows = append(rows, fmt.Sprintf("    {{%d, 0x%02x, %d, %d, %d, %d}, %s, %d, %s, %d},", h.Ver, h.Type, h.Seq, h.ReqID, h.Flags, h.CfgGen,
			c.bytesVar("tv_frame_body", bodies[i]), len(bodies[i]), c.bytesVar("tv_frame_wire", w), len(w)))
	}
	ping := func(id uint16) []byte {
		return codec.EncodeFrame([]byte{0}, wire.Header{Ver: 1, Type: wire.TypePing, ReqID: id}, []byte{1, 2, 3, 4})
	}
	badCRC := ping(20)
	badCRC[3] ^= 0x40
	if badCRC[3] == 0 {
		badCRC[3] = 1
	}
	short := append(codec.COBSEncode([]byte{0}, []byte{1, 2, 3}), 0)
	badCOBS := []byte{0, 0x05, 0x11, 0x22, 0}
	oversize := append(append([]byte{0}, bytes.Repeat([]byte{0x42}, codec.MaxEncodedLen(codec.MaxFrame)+10)...), 0)
	cat := func(p ...[]byte) []byte { return bytes.Join(p, nil) }
	ss := []stream{
		{Name: "garbage then two frames", Stream: hx(cat([]byte("ROM boot text\r\n"), ping(1), ping(2))), Frames: 2, ReqIDs: []int{1, 2}},
		{Name: "no leading delimiter: first frame lost", Stream: hx(cat(ping(3)[1:], ping(4))), Frames: 1, ReqIDs: []int{4}},
		{Name: "bad crc between good", Stream: hx(cat(ping(5), badCRC, ping(6))), Frames: 2, CRCErr: 1, ReqIDs: []int{5, 6}},
		{Name: "empty frames ignored", Stream: hx(cat([]byte{0, 0, 0}, ping(7), []byte{0, 0})), Frames: 1, ReqIDs: []int{7}},
		{Name: "short frame", Stream: hx(cat(short, ping(8))), Frames: 1, Short: 1, ReqIDs: []int{8}},
		{Name: "bad cobs", Stream: hx(cat(badCOBS, ping(9))), Frames: 1, COBSErr: 1, ReqIDs: []int{9}},
		{Name: "oversize", Stream: hx(cat(oversize, ping(10))), Frames: 1, Over: 1, ReqIDs: []int{10}},
	}
	// self-check against the reference decoder
	for _, s := range ss {
		b, _ := hex.DecodeString(s.Stream)
		d := codec.NewDecoder(codec.MaxFrame)
		var ids []int
		d.Feed(b, func(h wire.Header, _ []byte) { ids = append(ids, int(h.ReqID)) })
		st := d.Stats()
		if fmt.Sprint(ids) != fmt.Sprint(s.ReqIDs) || int(st.CRCErrors) != s.CRCErr || int(st.COBSErrors) != s.COBSErr || int(st.Oversize) != s.Over || int(st.Short) != s.Short {
			must(fmt.Errorf("stream %q: reference decoder disagrees: ids %v stats %+v", s.Name, ids, st))
		}
	}
	writeJSON("frames.json", map[string]any{"valid": vs, "streams": ss})
	fmt.Fprintf(&c.buf, "\ntypedef struct { struct { uint8_t ver, type; uint16_t seq, req_id; uint8_t flags, cfg_gen; } h; const uint8_t *body; size_t body_len; const uint8_t *wire; size_t wire_len; } tv_frame_t;\nstatic const tv_frame_t tv_frames[] = {\n%s\n};\n#define TV_FRAMES_N (sizeof tv_frames / sizeof tv_frames[0])\n", strings.Join(rows, "\n"))
	rows = nil
	for _, s := range ss {
		b, _ := hex.DecodeString(s.Stream)
		ids := make([]string, len(s.ReqIDs))
		for i, v := range s.ReqIDs {
			ids[i] = fmt.Sprint(v)
		}
		rows = append(rows, fmt.Sprintf("    {%q, %s, %d, %d, %d, %d, %d, %d, {%s}},", s.Name, c.bytesVar("tv_stream", b), len(b), s.Frames, s.CRCErr, s.COBSErr, s.Over, s.Short, strings.Join(ids, ",")))
	}
	fmt.Fprintf(&c.buf, "\ntypedef struct { const char *name; const uint8_t *stream; size_t len; int frames, crc_errors, cobs_errors, oversize, shortf; int req_ids[4]; } tv_stream_t;\nstatic const tv_stream_t tv_streams[] = {\n%s\n};\n#define TV_STREAMS_N (sizeof tv_streams / sizeof tv_streams[0])\n", strings.Join(rows, "\n"))
	c.close()
}

