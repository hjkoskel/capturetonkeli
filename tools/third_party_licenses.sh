#!/bin/sh
# Regenerate THIRD_PARTY_LICENSES.txt: the full licence texts (from the pinned
# ESP-IDF tree) of the non-Apache third-party code linked into the firmware
# image, as listed in THIRD_PARTY_NOTICES.md. Apache-2.0 components are covered
# by the copy in LICENSE. Usage: tools/third_party_licenses.sh [IDF_PATH]
set -eu
idf=${1:-${IDF_PATH:-/opt/esp-idf}}
want=$(cat "$(dirname "$0")/../firmware/idf-version.txt")
h=$idf/components/esp_common/include/esp_idf_version.h
have=v$(awk '/define ESP_IDF_VERSION_(MAJOR|MINOR|PATCH) /{printf "%s%s", sep, $3; sep="."}' "$h")
[ "$have" = "$want" ] || { echo "IDF at $idf is $have, pin is $want" >&2; exit 1; }
c=$idf/components
